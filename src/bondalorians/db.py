import json
import os
from datetime import UTC, datetime

from dotenv import load_dotenv
from sqlalchemy import create_engine, text

load_dotenv()


def get_engine():
    url = os.getenv("DATABASE_URL", "sqlite:///./bondalorians.db")
    return create_engine(url, future=True)


def init_db():
    engine = get_engine()
    with engine.begin() as conn:
        conn.execute(text("""CREATE TABLE IF NOT EXISTS pricing_runs (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            created_at VARCHAR(40) NOT NULL,
            request_json TEXT NOT NULL,
            result_json TEXT NOT NULL
        )""" if engine.dialect.name == "postgresql" else """CREATE TABLE IF NOT EXISTS pricing_runs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            created_at TEXT NOT NULL,
            request_json TEXT NOT NULL,
            result_json TEXT NOT NULL
        )"""))
    return engine


def save_run(request: dict, result: dict):
    engine = init_db()
    panel = result.get("panel")
    valuation = result.get("valuation")
    payload = {
        "explanation": result.get("explanation"),
        "error": result.get("error"),
        "valuation": {k: v for k, v in (valuation or {}).items() if k != "panel_with_metrics"},
        "comparables": panel[["bond_id", "similarity_score", "rationale"]].to_dict("records") if panel is not None and not panel.empty else [],
    }
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO pricing_runs (created_at, request_json, result_json) VALUES (:created, :request, :result)"), {
            "created": datetime.now(UTC).isoformat(),
            "request": json.dumps(request),
            "result": json.dumps(payload),
        })
